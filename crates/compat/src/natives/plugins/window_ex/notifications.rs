/// Resolve a notification name to its message number.
///
/// The reference looks the name up with `ncbPropAccessor::getIntValue(key,
/// -1)` on the `Window._Notifications` dictionary
/// (`reference/cpp/plugins/windowEx.cpp:751-758`), which is a plain
/// case-sensitive dictionary lookup
/// (`reference/cpp/core/tjs2/tjsObject.h:331-336` compares member names with
/// `TJS_strcmp`), so a differently-cased name misses and reads -1. The keys
/// are the bare `#key` names (`windowEx.cpp:801`), e.g. `"PAINT"`, not
/// `"WM_PAINT"`.
pub(crate) fn number_for(name: &str) -> Option<i64> {
    NOTIFICATIONS
        .iter()
        .find(|(key, _)| *key == name)
        .map(|(_, value)| *value)
}

/// Resolve a message number to its notification name. Later entries in the
/// reference order win, so the scan runs backwards.
pub(crate) fn name_for(number: i64) -> Option<&'static str> {
    NOTIFICATIONS
        .iter()
        .rev()
        .find(|(_, value)| *value == number)
        .map(|(name, _)| *name)
}

/// Build the `Window._Notifications` dictionary literal. Both directions are
/// emitted (name -> number and number -> name), exactly like the reference.
pub(crate) fn dictionary_literal() -> String {
    let mut out = String::from("%[");
    for (name, value) in NOTIFICATIONS {
        out.push_str(&format!(" \"{name}\" => {value}, {value} => \"{name}\","));
    }
    out.push_str(" ]");
    out
}
